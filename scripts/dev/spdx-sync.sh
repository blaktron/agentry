#!/usr/bin/env bash
# Refresh the embedded SPDX license and exception lists from
# the canonical license-list-data repository (CC0). Commit the result; V7
# accepts exactly what these files list.
set -euo pipefail
cd "$(dirname "$0")/../.."
out=pkg/manifest/spdx
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
curl -fsSL https://raw.githubusercontent.com/spdx/license-list-data/main/json/licenses.json -o "$tmp/licenses.json"
curl -fsSL https://raw.githubusercontent.com/spdx/license-list-data/main/json/exceptions.json -o "$tmp/exceptions.json"
python3 - "$tmp" "$out" <<'PY'
import json, sys
tmp, out = sys.argv[1], sys.argv[2]
lic = json.load(open(f"{tmp}/licenses.json"))
exc = json.load(open(f"{tmp}/exceptions.json"))
ver = lic.get("licenseListVersion", "unknown")
with open(f"{out}/licenses.txt", "w") as f:
    f.write(f"# SPDX license list {ver} — generated by scripts/dev/spdx-sync.sh; do not edit\n")
    f.write("# one identifier per line; a trailing '!' marks a deprecated identifier\n")
    for l in sorted(lic["licenses"], key=lambda x: x["licenseId"].lower()):
        f.write(l["licenseId"] + ("!" if l.get("isDeprecatedLicenseId") else "") + "\n")
with open(f"{out}/exceptions.txt", "w") as f:
    f.write(f"# SPDX exception list {ver} — generated by scripts/dev/spdx-sync.sh; do not edit\n")
    for e in sorted(exc["exceptions"], key=lambda x: x["licenseExceptionId"].lower()):
        f.write(e["licenseExceptionId"] + ("!" if e.get("isDeprecatedLicenseId") else "") + "\n")
print(f"spdx-sync: {len(lic['licenses'])} licenses, {len(exc['exceptions'])} exceptions, list version {ver}")
PY
