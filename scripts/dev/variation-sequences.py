#!/usr/bin/env python3
# Writes pkg/rules/variation_bases.go from Unicode's StandardizedVariants.txt and
# emoji-variation-sequences.txt (https://www.unicode.org/Public/<version>/ucd/ and
# ucd/emoji/):
#   scripts/dev/variation-sequences.py StandardizedVariants.txt emoji-variation-sequences.txt pkg/rules/variation_bases.go
import sys, collections
std, emo, out = sys.argv[1], sys.argv[2], sys.argv[3]
mask = collections.defaultdict(int)
def read(path):
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line or ";" not in line:
            continue
        seq = line.split(";", 1)[0].split()
        if len(seq) != 2:
            continue
        base, vs = int(seq[0], 16), int(seq[1], 16)
        if 0xFE00 <= vs <= 0xFE0F:
            mask[base] |= 1 << (vs - 0xFE00)
read(std); read(emo)
rows = sorted(mask.items())
with open(out, "w") as f:
    f.write("""// Code generated by scripts/dev/variation-sequences.py; DO NOT EDIT.

package rules

// variationBases is every base character of a standardized variation
// sequence (Unicode 16.0 StandardizedVariants.txt) or an emoji variation
// sequence (emoji-variation-sequences.txt) whose selector is in
// U+FE00..U+FE0F, with the selectors it takes as a bit mask (bit n is
// U+FE00+n), sorted by base for a binary search.
var variationBases = []variationBase{
""")
    for base, m in rows:
        f.write("\t{0x%04X, 0x%04X},\n" % (base, m))
    f.write("}\n")
print(len(rows), "bases")
