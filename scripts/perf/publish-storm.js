// §17.6 baseline: publish 20/min sustained with scan-queue age < 5 min.
//
// Two things are being measured, and the second is the interesting one. The
// submit call is cheap — it enqueues. What §17.6 actually constrains is
// whether the SCAN PIPELINE keeps up: at 20 publishes a minute, no version may
// sit in `scanning` for more than five minutes. So each iteration submits a
// version and then polls it to a terminal state, recording the wall time.
//
//   BASE_URL=https://staging.agentry.invalid AGENTRY_PAT=agy_… \
//     k6 run scripts/perf/publish-storm.js
//
// Not run by CI (see README.md) — staging only. It creates agents and
// versions; point it at a disposable environment.
import http from "k6/http";
import { check, sleep } from "k6";
import { Trend, Rate } from "k6/metrics";

const BASE_URL = __ENV.BASE_URL || "http://localhost:8080";
const PAT = __ENV.AGENTRY_PAT || "";
const NAMESPACE = __ENV.NAMESPACE || "";
const RATE = Number(__ENV.RATE || 20); // §17.6: 20 per minute
const DURATION = __ENV.DURATION || "10m";
const POLL_TIMEOUT_MS = Number(__ENV.POLL_TIMEOUT_MS || 5 * 60 * 1000);

const gateTrend = new Trend("publish_to_terminal_state", true);
const submitTrend = new Trend("submit_duration", true);
const timedOut = new Rate("scan_exceeded_5min");

export const options = {
  scenarios: {
    publish: {
      executor: "constant-arrival-rate",
      rate: RATE,
      timeUnit: "1m",
      duration: DURATION,
      preAllocatedVUs: 10,
      maxVUs: 60,
    },
  },
  thresholds: {
    http_req_failed: ["rate<0.01"],
    submit_duration: ["p(95)<1000"],
    // The §17.6 constraint, stated as a threshold: queue age under five
    // minutes means every version reaches a terminal state inside it.
    publish_to_terminal_state: ["p(95)<300000"],
    scan_exceeded_5min: ["rate<0.001"],
  },
};

function authHeaders() {
  if (!PAT) throw new Error("AGENTRY_PAT is required");
  return { Authorization: `Bearer ${PAT}`, "Content-Type": "application/json" };
}

export function setup() {
  const me = http.get(`${BASE_URL}/api/v1/user`, { headers: authHeaders() });
  if (me.status !== 200) {
    throw new Error(`AGENTRY_PAT is not usable: ${me.status} ${me.body}`);
  }
  const ns = NAMESPACE || me.json().handle;
  if (!ns) throw new Error("could not determine a namespace; set NAMESPACE");
  return { ns };
}

// A minimal, deliberately BENIGN prompt-agent. The harness measures pipeline
// throughput, not detection: content that gates to review would park versions
// in a review queue and make the timing meaningless.
function payload(name, version) {
  return {
    tag: null,
    files: {
      "agent.yaml":
        `schemaVersion: "1"\nname: ${name}\nkind: prompt-agent\nversion: ${version}\n` +
        `summary: Load-test agent generated by scripts/perf/publish-storm.js\n` +
        `license: Apache-2.0\npublish:\n  include: [agent.yaml, README.md]\n`,
      "README.md": `# ${name}\n\nGenerated by the §17.6 publish-storm harness.\n`,
    },
  };
}

export default function (data) {
  const ns = data.ns;
  const name = `perf-${__VU}-${__ITER}-${Date.now()}`;
  const version = "1.0.0";
  const headers = authHeaders();

  const created = http.post(
    `${BASE_URL}/api/v1/agents`,
    JSON.stringify({ namespace: ns, name, kind: "prompt-agent", visibility: "private" }),
    { headers },
  );
  if (!check(created, { "agent created": (r) => r.status === 201 })) return;

  const started = Date.now();
  const submitted = http.post(
    `${BASE_URL}/api/v1/agents/${ns}/${name}/versions`,
    JSON.stringify(payload(name, version)),
    { headers },
  );
  submitTrend.add(submitted.timings.duration);
  if (!check(submitted, { "version accepted": (r) => r.status === 202 || r.status === 201 })) return;

  // Poll to a terminal state. `scanning` is the state §17.6 bounds.
  const url = `${BASE_URL}/api/v1/agents/${ns}/${name}/versions/${version}`;
  for (;;) {
    const elapsed = Date.now() - started;
    if (elapsed > POLL_TIMEOUT_MS) {
      timedOut.add(true);
      gateTrend.add(elapsed);
      return;
    }
    const res = http.get(url, { headers });
    const status = res.status === 200 ? res.json().status : "";
    if (status && status !== "scanning" && status !== "submitted") {
      timedOut.add(false);
      gateTrend.add(Date.now() - started);
      return;
    }
    sleep(2);
  }
}
